BEGIN;

DO $$
BEGIN
    IF to_regclass('domain_templates') IS NOT NULL AND to_regclass('tasks') IS NULL THEN
        ALTER TABLE domain_templates RENAME TO tasks;
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL,
    label VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    created_date TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_modified_date TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

LOCK TABLE tasks IN ACCESS EXCLUSIVE MODE;

ALTER TABLE tasks
    ADD COLUMN IF NOT EXISTS created_by VARCHAR(255),
    ADD COLUMN IF NOT EXISTS last_modified_by VARCHAR(255),
    ADD COLUMN IF NOT EXISTS deleted_date TIMESTAMP(6) WITH TIME ZONE,
    ADD COLUMN IF NOT EXISTS deleted_by VARCHAR(255),
    ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

-- Historical usernames cannot be reconstructed from existing timestamps.
UPDATE tasks SET created_by = 'unknown' WHERE created_by IS NULL;
UPDATE tasks SET last_modified_by = 'unknown' WHERE last_modified_by IS NULL;
ALTER TABLE tasks ALTER COLUMN created_by SET NOT NULL;
ALTER TABLE tasks ALTER COLUMN last_modified_by SET NOT NULL;

-- Hibernate generated the original unique constraint name; discover it by column.
DO $$
DECLARE
    code_constraint RECORD;
BEGIN
    FOR code_constraint IN
        SELECT c.conname
        FROM pg_constraint c
        JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attname = 'code'
        WHERE c.conrelid = 'tasks'::regclass
          AND c.contype = 'u'
          AND c.conkey = ARRAY[a.attnum]::smallint[]
    LOOP
        EXECUTE format('ALTER TABLE tasks DROP CONSTRAINT %I', code_constraint.conname);
    END LOOP;
END
$$;

-- An already-audited legacy database retains its old partial index after table rename.
DROP INDEX IF EXISTS uk_domain_templates_active_code;
CREATE UNIQUE INDEX IF NOT EXISTS uk_tasks_active_code
    ON tasks (code) WHERE deleted_date IS NULL;

CREATE TABLE IF NOT EXISTS tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL UNIQUE,
    label VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    created_date TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_modified_date TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_by VARCHAR(255) NOT NULL,
    last_modified_by VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS nomenclatures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL UNIQUE,
    label VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    created_date TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_modified_date TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_by VARCHAR(255) NOT NULL,
    last_modified_by VARCHAR(255) NOT NULL,
    parent_id BIGINT REFERENCES nomenclatures(id),
    CONSTRAINT ck_nomenclatures_not_self CHECK (parent_id IS NULL OR parent_id <> id)
);

ALTER TABLE tasks
    ADD COLUMN IF NOT EXISTS status VARCHAR(255) NOT NULL DEFAULT 'TODO',
    ADD COLUMN IF NOT EXISTS priority VARCHAR(255) NOT NULL DEFAULT 'NORMAL',
    ADD COLUMN IF NOT EXISTS due_date DATE,
    ADD COLUMN IF NOT EXISTS assigned_to VARCHAR(255),
    ADD COLUMN IF NOT EXISTS nomenclature_id BIGINT REFERENCES nomenclatures(id);

CREATE TABLE IF NOT EXISTS task_tags (
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    tag_id BIGINT NOT NULL REFERENCES tags(id),
    PRIMARY KEY (task_id, tag_id)
);

CREATE INDEX IF NOT EXISTS idx_task_tags_tag ON task_tags(tag_id);
CREATE INDEX IF NOT EXISTS idx_tasks_nomenclature ON tasks(nomenclature_id);
CREATE INDEX IF NOT EXISTS idx_nomenclatures_parent ON nomenclatures(parent_id);
CREATE INDEX IF NOT EXISTS idx_tasks_status_priority ON tasks(status, priority) WHERE deleted_date IS NULL;
CREATE INDEX IF NOT EXISTS idx_tasks_due_date ON tasks(due_date) WHERE deleted_date IS NULL;

COMMIT;
